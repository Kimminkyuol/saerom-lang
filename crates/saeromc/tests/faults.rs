#[test]
fn faults_stop_with_message() {
    for (index, (what, source, wanted)) in CASES.iter().enumerate() {
        let shown = common::build_and_fail(source, &format!("faults{index}"));
        assert_eq!(&shown, wanted, "{what}");
    }
}

// 사용자 함수를 다녀온 뒤에도 오류는 부른 자리를 가리킨다.
#[test]
fn fault_points_at_caller() {
    let source = "수의 양수라는 것은:\n    만약 수가 0보다 크면:\n        수를 반환한다.\n\"{-1의 양수}\"을 출력한다.\n";
    let shown = common::build_and_fail_all(source, "faults_caller");
    assert!(shown.contains(".sr:4:"), "{shown}");
}
