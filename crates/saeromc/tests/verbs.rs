mod common;

const CASES: &[(&str, &str, &str)] = &[
    (
        "단항 -",
        "수는 3이다.\n상자는 2.5의 묶음이다.\n\"{-수} {-(상자의 1번째)} {-(수에 1을 더한 값)}\"을 출력한다.\n",
        "-3 -2.5 -4",
    ),
    (
        "-이다로 끝나는 동사",
        "글을 붙이다라는 것은:\n    \"[{글}]\"을 반환한다.\n\"{\"가\"를 붙인 값}\"을 출력한다.\n만약 \"가\"를 붙이면:\n    \" 참\"을 출력한다.\n",
        "[가] 참",
    ),
    (
        "-이다 서술어는 그대로",
        "수가 짝수이다라는 것은:\n    수를 2로 나눈 나머지가 0인지를 반환한다.\n\"{4가 짝수인지}\"를 출력한다.\n만약 3이 짝수가 아니면:\n    \" 홀수\"를 출력한다.\n",
        "참 홀수",
    ),
    (
        "삽입",
        "수들은 1과 2이다.\n수들의 1번째에 0을 삽입한다.\n수들의 (수들의 길이에 1을 더한 값)번째에 3을 삽입한다.\n\"{수들}\"을 출력한다.\n",
        "{0, 1, 2, 3}",
    ),
    (
        "바꾸지 못하면 없음",
        "수는 \"12\"를 정수로 바꾼 값이다.\n\"{수에 1을 더한 값} {\"가\"를 정수로 바꾼 값} {\"가\"를 논리값으로 바꾼 값}\"을 출력한다.\n",
        "13 없음 없음",
    ),
];

#[test]
fn verbs_behave() {
    for (index, (what, source, wanted)) in CASES.iter().enumerate() {
        let shown = common::build_and_run(source, &format!("verbs{index}"));
        assert_eq!(&shown, wanted, "{what}");
    }
}
