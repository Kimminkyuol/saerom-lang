#[test]
fn conjugation_matches_reference() {
    for &(stem, pos, wanted) in REFERENCE {
        let pos = if pos == "verb" {
            Pos::Verb
        } else {
            Pos::Descriptive
        };
        let made: Vec<String> = REGULAR_ENDINGS
            .iter()
            .map(|&ending| conjugate(stem, pos, ending).expect("활용형 없음"))
            .collect();
        assert_eq!(made.join("/"), wanted, "어간 {stem}");
    }
}

#[test]
fn quotative_has_no_conjugation() {
    assert_eq!(conjugate("뒤집", Pos::Verb, Ending::Quotative), None);
}
